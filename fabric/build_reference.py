"""Write fabric/kql/00_reference.kql: club and player names as KQL functions.

    uv run python -m fabric.build_reference

The Eventhouse only sees codes and ids (ASH, ASH-07). These lookups turn them into the
invented names from data/league/, so dashboard tiles read like a broadcast. Re-run after the
league changes; backend/tests/test_fabric.py fails if the file is out of date.
"""

from __future__ import annotations

from pathlib import Path

from engine.league import load_league
from engine.schema import League

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "fabric" / "kql" / "00_reference.kql"


def _s(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def reference_kql(league: League) -> str:
    clubs = ",\n".join(
        f"        {_s(c.code)}, {_s(c.name)}, {_s(c.primary_color)}" for c in league.clubs
    )
    players = ",\n".join(
        f"        {_s(p.id)}, {_s(p.name)}, {_s(p.position)}, {p.shirt}"
        for c in league.clubs
        for p in c.players
    )
    return f"""// Generated by fabric/build_reference.py from data/league/. Do not edit by hand.
// Club and player names for the invented {league.name}. Run before 02_functions.kql.

.create-or-alter function with (docstring = "Club code to name", folder = "pitchside")
Clubs() {{
    datatable(team: string, club: string, colour: string) [
{clubs}
    ]
}}

.create-or-alter function with (docstring = "Player id to name", folder = "pitchside")
Players() {{
    datatable(player_id: string, player: string, position: string, shirt: int) [
{players}
    ]
}}
"""


def main() -> None:
    OUT.write_text(reference_kql(load_league(ROOT / "data" / "league")), "utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
